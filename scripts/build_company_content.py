"""Builds the company content shown by the chat front end from the Word documents in Company_Documents/.

Nothing here is written by hand: the name, tagline, location and the twelve service pillars (name plus the document's own
"One-Line Summary") are read from the documents, so the front end can only show what the company has published.

    python scripts/build_company_content.py            # writes src/mpd_assistant/api/static/widget/company.json
"""

import html
import json
import re
import sys
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DOCS = ROOT / "Company_Documents"
OUT = ROOT / "src" / "mpd_assistant" / "api" / "static" / "widget" / "company.json"


def paragraphs(path: Path) -> list[str]:
    xml = zipfile.ZipFile(path).read("word/document.xml").decode("utf-8")
    result = []
    for block in re.findall(r"<w:p(?: [^>]*)?>.*?</w:p>", xml, flags=re.S):
        text = "".join(re.findall(r"<w:t(?: [^>]*)?>(.*?)</w:t>", block, flags=re.S))
        text = html.unescape(text).strip()
        if text:
            result.append(text)
    return result


def _plain(text: str) -> str:
    return re.sub(r"[^a-z]", "", text.lower())  # "One-Line Summary", "One‑Line Summary" and "OneLine Summary" all match


def after(lines: list[str], label: str) -> str:
    for i, line in enumerate(lines):
        if _plain(line) == _plain(label) and i + 1 < len(lines):
            return lines[i + 1]
    return ""


def starting(lines: list[str], prefix: str) -> str:
    for line in lines:
        if line.lower().startswith(prefix.lower()):
            return line[len(prefix):].strip(" :–-")
    return ""


def build() -> dict:
    profile = paragraphs(DOCS / "Company Profile.docx")
    title = starting(profile, "Title:")
    overview = starting(profile, "Overview:")
    tagline = next((l.strip("“”\"") for l in profile if l.startswith("“") and l.endswith("”")), "")
    presence = starting(profile, "Geographical Presence:")
    presence = re.sub(r"^[^\w]+", "", presence)

    pillars = []
    for path in sorted(DOCS.glob("*.docx")):
        lines = paragraphs(path)
        match = re.match(r"^Pillar (\d+):\s*(.+)$", lines[0]) if lines else None
        if not match:
            continue
        pillars.append({"number": int(match.group(1)), "name": match.group(2).strip(), "summary": after(lines, "One-Line Summary")})
    pillars.sort(key=lambda p: p["number"])

    return {
        "source": "Company_Documents/*.docx (generated by scripts/build_company_content.py)",
        "name": "Master Pro Dev",
        "title": title,
        "subtitle": title.split(" – ", 1)[1].strip() if " – " in title else "",
        "tagline": tagline,
        "overview": overview,
        "presence": presence,
        "pillars": pillars,
    }


if __name__ == "__main__":
    content = build()
    missing = [p["name"] for p in content["pillars"] if not p["summary"]]
    if len(content["pillars"]) != 12 or not content["tagline"] or missing:
        sys.exit(f"Unexpected documents: {len(content['pillars'])} pillars, tagline={bool(content['tagline'])}, no summary for {missing}")
    OUT.write_text(json.dumps(content, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} with {len(content['pillars'])} pillars")
