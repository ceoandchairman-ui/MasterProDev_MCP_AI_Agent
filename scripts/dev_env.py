"""Writes .env.dev with fresh random secrets for the local stack (deploy/compose.dev.yml). Never overwrites an existing file.

    python scripts/dev_env.py            # create .env.dev
    python scripts/dev_env.py --force    # replace it (stored data encrypted with the old keys becomes unreadable)

The file is ignored by git. These values are for a laptop only: production secrets are generated per environment and live
in Railway variables.
"""

import argparse
import secrets
import sys
from pathlib import Path

from mpd_assistant.core.crypto import generate_key

TARGET = Path(__file__).resolve().parent.parent / ".env.dev"


def build() -> str:
    lines = {
        "SECRET_KEY": secrets.token_urlsafe(32),
        "DATA_ENCRYPTION_KEY": generate_key(),
        "BLIND_INDEX_KEY": generate_key(),
        "MCP_SERVICE_KEY": secrets.token_urlsafe(32),
        "METRICS_TOKEN": secrets.token_urlsafe(24),
        "ADMIN_TOKEN": secrets.token_urlsafe(24),
        "EMAIL_INBOUND_TOKEN": secrets.token_urlsafe(24),
        "ADMIN_EMAIL": "dev@localhost",
        "ADMIN_PASSWORD": secrets.token_urlsafe(18),
        "REDIS_PASSWORD": "",
    }
    return "# Local development only. Generated by scripts/dev_env.py.\n" + "".join(f"{k}={v}\n" for k, v in lines.items())


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--force", action="store_true", help="replace an existing .env.dev")
    args = parser.parse_args(argv)
    if TARGET.exists() and not args.force:
        print(f"{TARGET.name} already exists; use --force to replace it.", file=sys.stderr)
        return 1
    TARGET.write_text(build(), encoding="utf-8")
    print(f"Wrote {TARGET.name}. Add provider keys (HUGGINGFACE_API_KEY, TWILIO_*, STRIPE_*) to it as you get them.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
